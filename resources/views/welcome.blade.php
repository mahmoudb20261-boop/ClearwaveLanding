        const key = source.trim();
        const leading = source.match(/^\s*/)[0];
        const trailing = source.match(/\s*$/)[0];

        node.nodeValue = leading + (language === 'ar' ? (translations[key] || key) : key) + trailing;
      }

      document.querySelectorAll('[data-en][data-ar]').forEach(element => {
        element.textContent = language === 'ar' ? element.dataset.ar : element.dataset.en;
      });

      document.querySelectorAll('[aria-label], [alt]').forEach(element => {
        ['aria-label', 'alt'].forEach(attribute => {
          if (!element.hasAttribute(attribute)) return;
          if (!originalAttributes.has(element)) originalAttributes.set(element, {});
          const saved = originalAttributes.get(element);

          if (!(attribute in saved)) saved[attribute] = element.getAttribute(attribute);

          const value = saved[attribute];
          element.setAttribute(attribute, language === 'ar' ? (translations[value] || value) : value);
        });
      });

      toggles.forEach(button => {
        button.textContent = language === 'ar' ? 'English' : 'العربية';
      });

      localStorage.setItem('clearwave-language', language);

      if (window.refreshClearwavePricing) {
        window.refreshClearwavePricing();
      }
    }

    toggles.forEach(button => {
      button.addEventListener('click', () => {
        applyLanguage(window.clearwaveLanguage === 'en' ? 'ar' : 'en');
      });
    });

    window.applyClearwaveLanguage = applyLanguage;
    applyLanguage(window.clearwaveLanguage);
  })();
